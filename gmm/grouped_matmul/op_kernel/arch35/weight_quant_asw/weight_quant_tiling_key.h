#ifndef __OP_KERNEL_WQGMM_ASW_TILING_KEY_H__
#define __OP_KERNEL_WQGMM_ASW_TILING_KEY_H__

#include "ascendc/host_api/tiling/template_argument.h"

#define WQGMM_VECTOR_ANTIQUANT 0
#define WQGMM_CUBE_ANTIQUANT 1

#define WQGMM_VDEFAULT 0
#define WQGMM_ASW 1

#define WQGMM_NO_TRANS 0
#define WQGMM_TRANS 1

#define WQGMM_NONE 0
#define WQGMM_PER_TENSOR 1
#define WQGMM_PER_CHANNEL 2
#define WQGMM_PER_GROUP 3
#define WQGMM_MX 4

#define WQGMM_ANTIQUANT_OFFSET_NOT_EXIST 0
#define WQGMM_ANTIQUANT_OFFSET_EXIST 2

#define WQGMM_ND 0
#define WQGMM_FRACTAL_NZ 1

#define WQGMM_NOT_SINGLE_MULTI_SINGLE 0
#define WQGMM_SINGLE_MULTI_SINGLE 1

// 模板参数
ASCENDC_TPL_ARGS_DECL(
    GroupedMatmul, // 算子OpType
    ASCENDC_TPL_UINT_DECL(W_TYPE, ASCENDC_TPL_4_BW, ASCENDC_TPL_UI_LIST, WQGMM_ND, WQGMM_FRACTAL_NZ),
    ASCENDC_TPL_UINT_DECL(OFFSET_OR_BIAS_EXIT, ASCENDC_TPL_4_BW, ASCENDC_TPL_UI_LIST, WQGMM_ANTIQUANT_OFFSET_NOT_EXIST,
                          WQGMM_ANTIQUANT_OFFSET_EXIST),
    ASCENDC_TPL_UINT_DECL(C_QUANT_TYPE, ASCENDC_TPL_4_BW, ASCENDC_TPL_UI_LIST, WQGMM_NONE),
    ASCENDC_TPL_UINT_DECL(W_QUANT_TYPE, ASCENDC_TPL_4_BW, ASCENDC_TPL_UI_LIST, WQGMM_NONE, WQGMM_PER_TENSOR,
                          WQGMM_PER_CHANNEL, WQGMM_PER_GROUP, WQGMM_MX),
    ASCENDC_TPL_UINT_DECL(WQ_B_TRANS, ASCENDC_TPL_2_BW, ASCENDC_TPL_UI_LIST, WQGMM_NO_TRANS, WQGMM_TRANS),
    ASCENDC_TPL_UINT_DECL(WQ_A_TRANS, ASCENDC_TPL_2_BW, ASCENDC_TPL_UI_LIST, WQGMM_NO_TRANS, WQGMM_TRANS),
    ASCENDC_TPL_UINT_DECL(TEMPLATE_CUSTOM_SC, ASCENDC_TPL_4_BW, ASCENDC_TPL_UI_LIST, WQGMM_NONE),
    ASCENDC_TPL_BOOL_DECL(IS_SINGLE_MULTI_SINGLE, WQGMM_SINGLE_MULTI_SINGLE, WQGMM_NOT_SINGLE_MULTI_SINGLE),
    ASCENDC_TPL_UINT_DECL(ALGORITHM_SUB_CATEGORY, ASCENDC_TPL_4_BW, ASCENDC_TPL_UI_LIST, WQGMM_VDEFAULT, WQGMM_ASW),
    ASCENDC_TPL_UINT_DECL(ALGORITHM_CATEGORY, ASCENDC_TPL_4_BW, ASCENDC_TPL_UI_LIST, WQGMM_VECTOR_ANTIQUANT,
                          WQGMM_CUBE_ANTIQUANT));
// 模板参数组合
// 用于调用GET_TPL_TILING_KEY获取TilingKey时，接口内部校验TilingKey是否合法
ASCENDC_TPL_SEL(ASCENDC_TPL_ARGS_SEL(
    ASCENDC_TPL_KERNEL_TYPE_SEL(ASCENDC_TPL_AIC_ONLY),
    ASCENDC_TPL_UINT_SEL(W_TYPE, ASCENDC_TPL_UI_LIST, WQGMM_FRACTAL_NZ),
    ASCENDC_TPL_UINT_SEL(OFFSET_OR_BIAS_EXIT, ASCENDC_TPL_UI_LIST, WQGMM_ANTIQUANT_OFFSET_NOT_EXIST),
    ASCENDC_TPL_UINT_SEL(C_QUANT_TYPE, ASCENDC_TPL_UI_LIST, WQGMM_NONE),
    ASCENDC_TPL_UINT_SEL(W_QUANT_TYPE, ASCENDC_TPL_UI_LIST, WQGMM_MX),
    ASCENDC_TPL_UINT_SEL(WQ_B_TRANS, ASCENDC_TPL_UI_LIST, WQGMM_TRANS),
    ASCENDC_TPL_UINT_SEL(WQ_A_TRANS, ASCENDC_TPL_UI_LIST, WQGMM_NO_TRANS),
    ASCENDC_TPL_UINT_SEL(TEMPLATE_CUSTOM_SC, ASCENDC_TPL_UI_LIST, WQGMM_NONE),
    ASCENDC_TPL_BOOL_SEL(IS_SINGLE_MULTI_SINGLE, WQGMM_NOT_SINGLE_MULTI_SINGLE),
    ASCENDC_TPL_UINT_SEL(ALGORITHM_SUB_CATEGORY, ASCENDC_TPL_UI_LIST, WQGMM_ASW),
    ASCENDC_TPL_UINT_SEL(ALGORITHM_CATEGORY, ASCENDC_TPL_UI_LIST, WQGMM_CUBE_ANTIQUANT)));
#endif
